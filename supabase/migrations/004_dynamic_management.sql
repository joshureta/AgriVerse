create or replace function public.set_lookup_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end;
$$;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'task_categories','task_priorities','task_statuses','schedule_statuses','farm_fields',
    'inventory_categories','measurement_units','pineapple_sizes','equipment_types'
  ] loop
    execute format('drop trigger if exists %I on public.%I', table_name || '_set_updated_at', table_name);
    execute format('create trigger %I before update on public.%I for each row execute procedure public.set_lookup_updated_at()', table_name || '_set_updated_at', table_name);
  end loop;
end $$;

create unique index if not exists inventory_active_name_category_key
