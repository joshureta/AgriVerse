update public.tasks t set
  task_name = coalesce(nullif(trim(t.description), ''), trim(t.category)),
  category_id = c.id,
  field_id = f.id,
  priority_id = p.id,
  status_id = s.id
from public.task_categories c, public.farm_fields f, public.task_priorities p, public.task_statuses s
where lower(c.category_name) = lower(trim(t.category))
  and lower(f.field_name) = lower(trim(t.field))
  and p.code = t.priority::text
  and s.code = t.status::text;

