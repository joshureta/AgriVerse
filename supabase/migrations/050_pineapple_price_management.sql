-- Record pineapple selling price changes without altering physical stock or past orders.
create table if not exists public.pineapple_price_changes (
  id bigint generated by default as identity primary key,
  pineapple_size_id bigint not null references public.pineapple_sizes(id) on delete restrict,
  old_price numeric(10, 2) not null check (old_price >= 0),
  new_price numeric(10, 2) not null check (new_price > 0),
  changed_by uuid references public.profiles(id) on delete set null,
  changed_at timestamptz not null default now()
);

create index if not exists pineapple_price_changes_size_time_idx
  on public.pineapple_price_changes (pineapple_size_id, changed_at desc);

alter table public.pineapple_price_changes enable row level security;
revoke all on table public.pineapple_price_changes from anon, authenticated;
grant all on table public.pineapple_price_changes to service_role;
grant usage, select on sequence public.pineapple_price_changes_id_seq to service_role;

create or replace function public.update_pineapple_selling_price(
  p_size_id bigint,
  p_new_price numeric,
  p_expected_price numeric,
  p_changed_by uuid
)
returns public.pineapple_sizes
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_size public.pineapple_sizes%rowtype;
  v_old_price numeric(10, 2);
begin
  if p_new_price is null or p_new_price <= 0 or p_new_price > 99999999.99
     or p_new_price <> round(p_new_price, 2) then
    raise exception 'Selling price must be greater than zero, with no more than two decimal places';
  end if;

  select * into v_size from public.pineapple_sizes
  where id = p_size_id and status = true for update;
  if not found then
    raise exception 'Pineapple size was not found or is inactive' using errcode = 'P0002';
  end if;
  if v_size.selling_price is distinct from p_expected_price then
    raise exception 'Pineapple price changed while editing' using errcode = 'P0001';
  end if;
  if v_size.selling_price = p_new_price then
    return v_size;
  end if;

  v_old_price := v_size.selling_price;
  update public.pineapple_sizes set selling_price = p_new_price
  where id = p_size_id returning * into v_size;

  insert into public.pineapple_price_changes
    (pineapple_size_id, old_price, new_price, changed_by)
  values (p_size_id, v_old_price, p_new_price, p_changed_by);
  return v_size;
end;
$$;

revoke all on function public.update_pineapple_selling_price(bigint, numeric, numeric, uuid)
  from public, anon, authenticated;
grant execute on function public.update_pineapple_selling_price(bigint, numeric, numeric, uuid)
  to service_role;

notify pgrst, 'reload schema';
