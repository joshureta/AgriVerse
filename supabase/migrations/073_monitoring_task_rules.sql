-- Reading-based task rules, editable in Supabase. Run after 072 in the main
-- AgriVerse project (the sensor tables live in the same project).
--
-- Every insert into sensor_readings or soil_readings checks the enabled rules.
-- When the three most recent readings from that device and field (all from the
-- last 10 minutes) meet a rule, the rule's task is created and assigned with
-- the same worker/slot logic as before. A failed rule check never blocks the
-- reading insert. Each rule creates at most one task per field per Manila day.

create table if not exists public.monitoring_task_rules (
  id bigint generated by default as identity primary key,
  rule_name text not null check (char_length(rule_name) between 1 and 120),
  kind text not null check (kind ~ '^[a-z][a-z0-9_]{1,40}$'),
  field_name text,
  reading text not null check (reading in
    ('soil_moisture', 'temperature_c', 'humidity_percent', 'soil_temperature_c')),
  comparison text not null check (comparison in ('above', 'below')),
  threshold numeric not null,
  also_reading text check (also_reading in
    ('soil_moisture', 'temperature_c', 'humidity_percent', 'soil_temperature_c')),
  also_comparison text check (also_comparison in ('above', 'below')),
  also_threshold numeric,
  category_name text not null,
  priority_code text not null check (priority_code in ('low', 'medium', 'high', 'urgent')),
  activity_type text,
  task_description text not null check (char_length(task_description) between 1 and 1500),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((also_reading is null and also_comparison is null and also_threshold is null)
    or (also_reading is not null and also_comparison is not null and also_threshold is not null)),
  check (kind not in ('pest_disease', 'crop_check'))
);
create unique index if not exists monitoring_task_rules_kind_field_idx
  on public.monitoring_task_rules (kind, (coalesce(field_name, '*')));
drop trigger if exists monitoring_task_rules_set_updated_at on public.monitoring_task_rules;
create trigger monitoring_task_rules_set_updated_at before update on public.monitoring_task_rules
  for each row execute procedure public.set_lookup_updated_at();
alter table public.monitoring_task_rules enable row level security;
revoke all on public.monitoring_task_rules from public, anon, authenticated;
grant all on public.monitoring_task_rules to service_role;

