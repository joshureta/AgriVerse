const assert = require("node:assert/strict");
const { test } = require("node:test");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const { PGlite } = require("@electric-sql/pglite");

const migration = (name) => readFileSync(join(__dirname, "../../supabase/migrations", name), "utf8");

// A database with the tables the rule migrations need, then the migrations (073 runs twice to check it re-runs cleanly).
async function setupDatabase(db, extraMigrations = []) {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create function public.set_lookup_updated_at() returns trigger language plpgsql as $$
        begin new.updated_at = now(); return new; end $$;
      create table profiles(id uuid primary key, role text, worker_category text,
        name_confirmed_at timestamptz, onboarding_completed_at timestamptz,
        must_change_password boolean default false);
      create table farm_fields(id bigint primary key, field_name text, status boolean);
      create table task_categories(id bigint primary key, category_name text, status boolean);
      create table task_priorities(id bigint primary key, code text, status boolean);
      create table task_statuses(id bigint primary key, code text, status boolean);
      create table schedule_statuses(id bigint primary key, code text, status boolean);
      create table tasks(id bigint generated by default as identity primary key,
        assigned_worker_id uuid, category_id bigint, field_id bigint, priority_id bigint,
        status_id bigint, task_name text, estimated_duration_minutes integer,
        description text, activity_type text, completed_at timestamptz,
        created_at timestamptz default now());
      create table schedules(id bigint generated by default as identity primary key,
        task_id bigint references tasks(id), schedule_date date, start_time time,
        end_time time, location text, status_id bigint, notes text);
      create table sensor_device_fields(device_id text primary key, field_name text);
      create table sensor_readings(id bigint generated by default as identity primary key,
        device_id text, field_name text, temperature_c numeric, soil_temperature_c numeric,
        humidity_percent numeric, soil_moisture numeric, created_at timestamptz default now());
      create table soil_readings(id uuid default gen_random_uuid() primary key,
        device_id text, field_name text, moisture_raw integer not null, moisture_percent numeric,
        created_at timestamptz default now());
      create function public.set_sensor_reading_field() returns trigger language plpgsql as $$
        begin new.field_name := (select field_name from sensor_device_fields where device_id = new.device_id);
        return new; end $$;
      create trigger sensor_readings_set_field before insert on sensor_readings
        for each row execute function set_sensor_reading_field();
      create trigger soil_readings_set_field before insert on soil_readings
        for each row execute function set_sensor_reading_field();
      insert into sensor_device_fields values ('ESP32_001','Field A'),('ESP32_002','Field A');
      insert into farm_fields values (1,'Field A',true);
      insert into task_categories values (1,'Irrigation',true),(2,'Monitoring',true),(3,'Pest & Disease',true);
      insert into task_priorities values (1,'medium',true),(2,'high',true),(3,'low',true);
      insert into task_statuses values (1,'pending',true),(2,'in_progress',true),
        (3,'completed',true),(4,'cancelled',true),(5,'awaiting_approval',true);
      insert into schedule_statuses values (1,'scheduled',true),(2,'cancelled',true);
      insert into profiles(id, role, worker_category, name_confirmed_at, onboarding_completed_at) values
        ('11111111-1111-4111-8111-111111111111','farm_worker','crop_management_worker',now(),now());
    `);
    for (const name of ["070_monitoring_task_automation.sql", "071_overdue_monitoring_task_findings.sql",
      "072_assign_new_monitoring_findings.sql", "073_monitoring_task_rules.sql", "073_monitoring_task_rules.sql",
      ...extraMigrations]) {
      await db.exec(migration(name));
    }
}

test("reading rules in Supabase create the matching task once, and disabled rules do nothing", async () => {
  const db = new PGlite();
  try {
    await setupDatabase(db);
    assert.equal((await db.query("select count(*)::int n from monitoring_task_rules")).rows[0].n, 10);
    const tasks = async () => (await db.query(`select t.task_name, c.category_name, p.code priority, t.activity_type,
      t.automation_kind, t.description from tasks t join task_categories c on c.id=t.category_id
      join task_priorities p on p.id=t.priority_id order by t.id`)).rows;
    const soil = (pct, secondsAgo) => db.query(`insert into soil_readings(device_id, moisture_raw, moisture_percent, created_at)
      values ('ESP32_001', 3100, $1, now() - make_interval(secs => $2))`, [pct, secondsAgo]);
    const air = (values, secondsAgo, device = "ESP32_001") => db.query(`insert into sensor_readings
      (device_id, temperature_c, humidity_percent, soil_moisture, soil_temperature_c, created_at)
      values ($6, $1, $2, $3, $4, now() - make_interval(secs => $5))`, [...values, secondsAgo, device]);

    // Two low readings are not enough; the third creates the Irrigation task.
    await soil(28, 30); await soil(27, 20);
    assert.equal((await tasks()).length, 0);
    await soil(27, 10);
    let rows = await tasks();
    assert.equal(rows.length, 1);
    assert.deepEqual([rows[0].task_name, rows[0].category_name, rows[0].priority, rows[0].automation_kind],
      ["Irrigation - Field A", "Irrigation", "high", "irrigation"]);
    assert.match(rows[0].description, /below 35 \(last 3: 27, 27, 28\)/);
    // The same condition later that day does not add a second task.
    await soil(26, 0);
    assert.equal((await tasks()).length, 1);
    const finding = (await db.query("select status, notified_at from monitoring_task_findings")).rows[0];
    assert.equal(finding.status, "assigned");
    assert.equal(finding.notified_at, null);

    // Humid air alone creates a Pest & Disease inspection; mixed values do not.
    await air([25, 95, 40, 28], 30); await air([25, 80, 40, 28], 20); await air([25, 95, 40, 28], 10);
    assert.equal((await tasks()).length, 1);
    await air([25, 96, 40, 28], 5); await air([25, 97, 40, 28], 1);
    rows = await tasks();
    assert.equal(rows.length, 2);
    assert.deepEqual([rows[1].category_name, rows[1].activity_type, rows[1].automation_kind],
      ["Pest & Disease", "inspection", "high_humidity"]);

    // Disabled rules (cold air ships disabled) never create a task.
    await air([12, 50, 40, 28], 3, "ESP32_002"); await air([12, 50, 40, 28], 2, "ESP32_002"); await air([12, 50, 40, 28], 1, "ESP32_002");
    assert.equal((await tasks()).filter((t) => t.automation_kind === "cold_stress").length, 0);
    await db.exec("update monitoring_task_rules set enabled = true where kind = 'cold_stress'");
    await air([11, 50, 40, 28], 0, "ESP32_002");
    assert.equal((await tasks()).filter((t) => t.automation_kind === "cold_stress").length, 1);

    // A broken rule cannot block a reading from saving.
    await db.exec("update task_categories set status = false");
    await db.exec("update monitoring_task_rules set threshold = 100 where kind = 'hot_soil'");
    await air([25, 50, 40, 101], 0);
    assert.equal((await db.query("select count(*)::int n from sensor_readings")).rows[0].n, 10);
    // Readings with no field are ignored.
    await db.query("insert into soil_readings(device_id, moisture_raw, moisture_percent) values ('OTHER', 3100, 5)");
    assert.equal((await tasks()).length, 3);
  } finally { await db.close(); }
});

test("a rule turned off while its finding waits for a worker creates no task (074)", async () => {
  const db = new PGlite();
  try {
    // 074 runs twice to check it re-runs cleanly.
    await setupDatabase(db, ["074_monitoring_rule_settings.sql", "074_monitoring_rule_settings.sql"]);
    const flags = (await db.query(`select kind from monitoring_task_rules where needs_review order by kind`)).rows.map((r) => r.kind);
    assert.deepEqual(flags.filter((k, i) => flags.indexOf(k) === i), ["cold_stress", "high_humidity", "hot_soil", "waterlogging_rot"]);

    // No eligible worker: the low-moisture finding waits in the queue.
    await db.exec("update profiles set onboarding_completed_at = null");
    for (const secondsAgo of [30, 20, 10]) {
      await db.query(`insert into soil_readings(device_id, moisture_raw, moisture_percent, created_at)
        values ('ESP32_001', 3100, 20, now() - make_interval(secs => $1))`, [secondsAgo]);
    }
    const status = async () => (await db.query("select status from monitoring_task_findings")).rows.map((r) => r.status);
    assert.deepEqual(await status(), ["queued"]);
    const retry = () => db.query(`select public.record_monitoring_task_finding(f.event_key, ff.field_name, f.source, f.kind,
      f.evidence, f.observed_at) r from monitoring_task_findings f join farm_fields ff on ff.id = f.field_id`);

    // The admin turns the Field A rule off, then a worker becomes free: the retry dismisses it.
    await db.exec("update monitoring_task_rules set enabled = false where kind = 'irrigation' and field_name = 'Field A'");
    await db.exec("update profiles set onboarding_completed_at = now()");
    assert.equal((await retry()).rows[0].r.status, "dismissed");
    assert.deepEqual(await status(), ["dismissed"]);
    assert.equal((await db.query("select count(*)::int n from tasks")).rows[0].n, 0);
    // Turning it back on does not revive the dismissed finding.
    await db.exec("update monitoring_task_rules set enabled = true where kind = 'irrigation'");
    assert.equal((await retry()).rows[0].r.status, "dismissed");
    assert.equal((await db.query("select count(*)::int n from tasks")).rows[0].n, 0);
  } finally { await db.close(); }
});
