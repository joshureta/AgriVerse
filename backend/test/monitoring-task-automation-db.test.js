const assert = require("node:assert/strict");
const { test } = require("node:test");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const { PGlite } = require("@electric-sql/pglite");

test("finding queues without a worker, then assigns one task and suppresses duplicates", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create function public.set_lookup_updated_at() returns trigger language plpgsql as $$
        begin new.updated_at = now(); return new; end $$;
      create table profiles(id uuid primary key, role text, worker_category text,
        name_confirmed_at timestamptz, onboarding_completed_at timestamptz,
        must_change_password boolean default false);
      create table farm_fields(id bigint primary key, field_name text, status boolean);
      create table task_categories(id bigint primary key, category_name text, status boolean);
      create table task_priorities(id bigint primary key, code text, status boolean);
      create table task_statuses(id bigint primary key, code text, status boolean);
      create table schedule_statuses(id bigint primary key, code text, status boolean);
      create table tasks(id bigint generated by default as identity primary key,
        assigned_worker_id uuid, category_id bigint, field_id bigint, priority_id bigint,
        status_id bigint, task_name text, estimated_duration_minutes integer,
        description text, activity_type text, completed_at timestamptz,
        created_at timestamptz default now());
      create table schedules(id bigint generated by default as identity primary key,
        task_id bigint references tasks(id), schedule_date date, start_time time,
        end_time time, location text, status_id bigint, notes text);
      insert into farm_fields values (1,'Field A',true);
      insert into task_categories values (1,'Irrigation',true),(2,'Monitoring',true),(3,'Pest & Disease',true);
      insert into task_priorities values (1,'medium',true),(2,'high',true);
      insert into task_statuses values (1,'pending',true),(2,'in_progress',true),
        (3,'completed',true),(4,'cancelled',true),(5,'awaiting_approval',true);
      insert into schedule_statuses values (1,'scheduled',true),(2,'cancelled',true);
    `);
    const migration = readFileSync(join(__dirname, "../../supabase/migrations/070_monitoring_task_automation.sql"), "utf8");
    await db.exec(migration);
    await db.exec(migration);
    const sql = "select public.record_monitoring_task_finding($1,$2,$3,$4,$5,$6) result";
    const args = ["environmental:Field A:today:irrigation", "Field A", "environmental", "irrigation",
      "Three low readings; check the soil.", new Date().toISOString()];
    const queued = (await db.query(sql, args)).rows[0].result;
    assert.equal(queued.status, "queued");
    assert.equal((await db.query("select count(*)::int n from tasks")).rows[0].n, 0);

    await db.exec(`insert into profiles(id, role, worker_category, name_confirmed_at, onboarding_completed_at) values
      ('11111111-1111-4111-8111-111111111111','farm_worker','crop_management_worker',now(),now());`);
    const assigned = (await db.query(sql, args)).rows[0].result;
    assert.equal(assigned.status, "assigned");
    assert.equal(assigned.created, true);
    assert.ok(assigned.task_id);
    assert.equal((await db.query(sql, args)).rows[0].result.created, false);
    assert.equal((await db.query("select count(*)::int n from tasks")).rows[0].n, 1);
    assert.equal((await db.query("select count(*)::int n from schedules")).rows[0].n, 1);
    assert.equal((await db.query("select automation_source from tasks where id=$1", [assigned.task_id])).rows[0].automation_source, "environmental");

    const sameIssue = [...args]; sameIssue[0] = "environmental:Field A:tomorrow:irrigation";
    assert.equal((await db.query(sql, sameIssue)).rows[0].result.status, "covered");
    assert.equal((await db.query("select count(*)::int n from tasks")).rows[0].n, 1);

    const secondIssue = ["environmental:Field A:today:environment_check", "Field A", "environmental",
      "environment_check", "Three high temperature readings; inspect crops.", new Date().toISOString()];
    const second = (await db.query(sql, secondIssue)).rows[0].result;
    assert.equal(second.status, "assigned");
    const schedules = (await db.query("select schedule_date, start_time, end_time from schedules order by schedule_date, start_time")).rows;
    assert.equal(schedules.length, 2);
    assert.ok(schedules[0].schedule_date !== schedules[1].schedule_date || schedules[0].end_time <= schedules[1].start_time);

    // Migration 070 incorrectly covered a fresh finding with an overdue task.
    const oldTask = (await db.query(`insert into tasks
      (assigned_worker_id, category_id, field_id, priority_id, status_id, task_name)
      values ('11111111-1111-4111-8111-111111111111',3,1,2,1,'Pest & Disease - Field A')
      returning id`)).rows[0].id;
    await db.query(`insert into schedules
      (task_id,schedule_date,start_time,end_time,location,status_id)
      values ($1,(now() at time zone 'Asia/Manila')::date - 4,'15:00','16:00','Field A',1)`, [oldTask]);
    const pest = ["crop_health:Field A:pest:1", "Field A", "crop_health", "pest_disease",
      "Possible pest damage; inspect the crop.", new Date().toISOString()];
    assert.equal((await db.query(sql, pest)).rows[0].result.status, "covered");

    const fix = readFileSync(join(__dirname, "../../supabase/migrations/071_overdue_monitoring_task_findings.sql"), "utf8");
    await db.exec(fix);
    await db.exec(fix);
    let finding = (await db.query("select status, task_id, blocked_by_task_id from monitoring_task_findings where event_key=$1", [pest[0]])).rows[0];
    assert.equal(finding.status, "queued");
    assert.equal(finding.task_id, null);
    assert.equal(finding.blocked_by_task_id, oldTask);
    const blocked = (await db.query(sql, pest)).rows[0].result;
    assert.equal(blocked.status, "queued");
    assert.equal(blocked.blocked_by_task_id, oldTask);
    assert.equal(blocked.created, false);

    // Rescheduling makes the existing task valid coverage, without a duplicate.
    await db.query(`update schedules set schedule_date=(now() at time zone 'Asia/Manila')::date + 1
      where task_id=$1`, [oldTask]);
    assert.equal((await db.query(sql, pest)).rows[0].result.status, "covered");
    finding = (await db.query("select status, blocked_by_task_id from monitoring_task_findings where event_key=$1", [pest[0]])).rows[0];
    assert.equal(finding.status, "covered");
    assert.equal(finding.blocked_by_task_id, null);

    // Completion after a fresh observation also resolves an overdue blocker.
    await db.query(`update schedules set schedule_date=(now() at time zone 'Asia/Manila')::date - 4
      where task_id=$1`, [oldTask]);
    const pestAgain = [...pest]; pestAgain[0] = "crop_health:Field A:pest:2";
    assert.equal((await db.query(sql, pestAgain)).rows[0].result.blocked_by_task_id, oldTask);
    await db.query("update tasks set status_id=3, completed_at=now() where id=$1", [oldTask]);
    assert.equal((await db.query(sql, pestAgain)).rows[0].result.status, "covered");

    // Cancelling overdue work releases the finding for a new assignment.
    const cancelledTask = (await db.query(`insert into tasks
      (assigned_worker_id, category_id, field_id, priority_id, status_id, task_name, automation_kind)
      values ('11111111-1111-4111-8111-111111111111',2,1,1,1,'Monitoring - Field A','crop_check')
      returning id`)).rows[0].id;
    await db.query(`insert into schedules
      (task_id,schedule_date,start_time,end_time,location,status_id)
      values ($1,(now() at time zone 'Asia/Manila')::date - 4,'15:00','16:00','Field A',1)`, [cancelledTask]);
    const crop = ["crop_health:Field A:crop:1", "Field A", "crop_health", "crop_check",
      "Unhealthy crop condition; inspect plants.", new Date().toISOString()];
    assert.equal((await db.query(sql, crop)).rows[0].result.blocked_by_task_id, cancelledTask);
    await db.query("update tasks set status_id=4 where id=$1", [cancelledTask]);
    await db.query("update schedules set status_id=2 where task_id=$1", [cancelledTask]);
    const reassigned = (await db.query(sql, crop)).rows[0].result;
    assert.equal(reassigned.status, "assigned");
    assert.notEqual(reassigned.task_id, cancelledTask);

    // A fresh finding must get new current/future work even when older work
    // for that field and category is still overdue.
    const overdueTask = (await db.query(`insert into tasks
      (assigned_worker_id, category_id, field_id, priority_id, status_id, task_name)
      values ('11111111-1111-4111-8111-111111111111',3,1,2,1,'Pest & Disease - Field A')
      returning id`)).rows[0].id;
    await db.query(`insert into schedules
      (task_id,schedule_date,start_time,end_time,location,status_id)
      values ($1,(now() at time zone 'Asia/Manila')::date - 4,'15:00','16:00','Field A',1)`, [overdueTask]);
    const newPest = [...pest]; newPest[0] = "crop:inspection-1:pest_disease";
    assert.equal((await db.query(sql, newPest)).rows[0].result.blocked_by_task_id, overdueTask);
    const currentAssignment = readFileSync(join(__dirname,
      "../../supabase/migrations/072_assign_new_monitoring_findings.sql"), "utf8");
    await db.exec(currentAssignment);
    await db.exec(currentAssignment);
    assert.equal((await db.query("select blocked_by_task_id from monitoring_task_findings where event_key=$1", [newPest[0]])).rows[0].blocked_by_task_id, null);
    const freshAssignment = (await db.query(sql, newPest)).rows[0].result;
    assert.equal(freshAssignment.status, "assigned");
    assert.equal(freshAssignment.created, true);
    assert.notEqual(freshAssignment.task_id, overdueTask);
    const futureSchedule = (await db.query(`select schedule_date + start_time > now() at time zone 'Asia/Manila' as future
      from schedules where task_id=$1`, [freshAssignment.task_id])).rows[0].future;
    assert.equal(futureSchedule, true);
    assert.equal((await db.query(sql, newPest)).rows[0].result.created, false);

    const anotherInspection = [...newPest]; anotherInspection[0] = "crop:inspection-2:pest_disease";
    const anotherAssignment = (await db.query(sql, anotherInspection)).rows[0].result;
    assert.equal(anotherAssignment.status, "assigned");
    assert.notEqual(anotherAssignment.task_id, freshAssignment.task_id);
  } finally { await db.close(); }
});
