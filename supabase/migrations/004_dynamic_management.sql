update public.inventory_items i set
  inventory_category_id = c.id,
  unit_id = u.id
from public.inventory_categories c, public.measurement_units u
where lower(c.category_name) = lower(trim(i.item_type))
  and u.abbreviation = case c.code
    when 'fertilizer' then 'bags' when 'pesticide' then 'L'
    when 'equipment' then 'units' else 'pcs' end;

