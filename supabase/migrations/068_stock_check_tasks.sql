-- Stock Check: a task category in which a farm worker physically counts pineapple stock
-- by size and condition. It follows the normal task flow
-- (Pending -> In Progress -> Awaiting Approval -> Completed).
--
-- start_stock_check_task       starts the task and records the system quantity of each size (the snapshot)
-- capture_stock_check_snapshot records the snapshot again (used when the admin returns a count for recount)
-- save_stock_check_submission  stores the worker's counts and photo evidence while the task is in progress
-- approve_stock_check_task     completes the task and corrects Pineapple Stock; each write-off is logged
--
-- Pineapple Stock changes only on approval. Only the difference found is applied
-- (good count minus snapshot), so orders placed during the count are kept.

insert into public.task_categories (category_name, description)
values ('Stock Check', 'Physical count of pineapple stock by condition')
on conflict do nothing;

-- Conditions a counted pineapple can be in. Only conditions with stays_in_stock remain sellable.
create table if not exists public.stock_conditions (
  id bigint generated by default as identity primary key,
  code text not null unique,
  condition_name text not null,
  stays_in_stock boolean not null default false,
  needs_photo boolean not null default true,
  sort_order integer not null default 0,
  status boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.stock_conditions (code, condition_name, stays_in_stock, needs_photo, sort_order) values
  ('good', 'Good', true, false, 10),
  ('minor_damage', 'Minor damage', false, true, 20),
  ('overripe', 'Overripe', false, true, 30),
  ('spoiled', 'Spoiled', false, true, 40),
  ('pest_disease', 'Pest or disease damage', false, true, 50)
on conflict (code) do nothing;

-- System quantity of each pineapple size when the count started. Never shown to the worker in a blind count.
create table if not exists public.stock_check_snapshots (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  pineapple_size_id bigint not null references public.pineapple_sizes(id) on delete restrict,
  inventory_item_id bigint references public.inventory_items(id) on delete set null,
  system_quantity integer not null check (system_quantity >= 0),
  captured_at timestamptz not null default now(),
  unique (task_id, pineapple_size_id)
);

-- One row per task, size and condition. worker_quantity keeps what the worker submitted
-- when the admin corrects a count before approving.
create table if not exists public.stock_check_counts (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  pineapple_size_id bigint not null references public.pineapple_sizes(id) on delete restrict,
  condition_id bigint not null references public.stock_conditions(id) on delete restrict,
  quantity integer not null check (quantity >= 0),
  worker_quantity integer not null check (worker_quantity >= 0),
  damage_types text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (task_id, pineapple_size_id, condition_id)
);

create table if not exists public.stock_check_photos (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  pineapple_size_id bigint not null references public.pineapple_sizes(id) on delete restrict,
  condition_id bigint not null references public.stock_conditions(id) on delete restrict,
  image_url text not null,
  storage_path text,
  created_at timestamptz not null default now()
);

create index if not exists stock_check_counts_task_idx on public.stock_check_counts (task_id);
create index if not exists stock_check_photos_task_idx on public.stock_check_photos (task_id);

-- Why a stock movement happened. Movements from orders, harvests and admin edits keep a null reason.
alter table public.inventory_stock_movements
  add column if not exists reason text,
  add column if not exists condition_id bigint references public.stock_conditions(id) on delete set null,
  add column if not exists task_id bigint references public.tasks(id) on delete set null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'inventory_stock_movements_reason_check') then
    alter table public.inventory_stock_movements add constraint inventory_stock_movements_reason_check
      check (reason is null or reason in ('stock_check', 'stock_check_unaccounted', 'stock_check_found'));
  end if;
end $$;

create index if not exists inventory_stock_movements_task_idx on public.inventory_stock_movements (task_id);

-- The stock movement trigger now also copies the reason, condition and task that the
-- approval function sets for its own transaction. Other updates leave them empty.
create or replace function public.record_inventory_stock_movement()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.quantity is distinct from old.quantity then
    insert into public.inventory_stock_movements (
      inventory_item_id, movement_type, quantity, quantity_before, quantity_after,
      reason, condition_id, task_id
    ) values (
      new.id,
      case when new.quantity > old.quantity then 'stock_in' else 'stock_out' end,
      abs(new.quantity - old.quantity), old.quantity, new.quantity,
      nullif(current_setting('agriverse.movement_reason', true), ''),
      nullif(current_setting('agriverse.movement_condition_id', true), '')::bigint,
      nullif(current_setting('agriverse.movement_task_id', true), '')::bigint
    );
  end if;
  return new;
end;
$$;

-- The active Pineapple Stock item for a size, or null when there is none yet.
create or replace function public.stock_check_item_for_size(p_size_id bigint)
returns bigint language sql stable security definer set search_path = '' as $$
  select ii.id
  from public.inventory_items ii
  join public.inventory_categories c on c.id = ii.inventory_category_id and c.code = 'pineapple'
  join public.pineapple_inventory pi on pi.inventory_id = ii.id
  where pi.size_id = p_size_id and ii.archived_at is null
  order by ii.id
  limit 1;
$$;

-- Records the current system quantity of every active pineapple size. Every Stock Check counts all sizes.
create or replace function public.capture_stock_check_snapshot(p_task_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_size record;
  v_item_id bigint;
  v_quantity integer;
begin
  delete from public.stock_check_snapshots where task_id = p_task_id;

  for v_size in
    select ps.id, ps.size_name
    from public.pineapple_sizes ps
    where ps.status = true
    order by ps.id
  loop
    v_item_id := public.stock_check_item_for_size(v_size.id);
    v_quantity := 0;
    if v_item_id is not null then
      select quantity into v_quantity from public.inventory_items where id = v_item_id;
    end if;
    insert into public.stock_check_snapshots (task_id, pineapple_size_id, inventory_item_id, system_quantity)
    values (p_task_id, v_size.id, v_item_id, coalesce(v_quantity, 0));
  end loop;
end;
$$;

-- Starts a pending Stock Check task and records the snapshot in the same transaction.
create or replace function public.start_stock_check_task(p_task_id bigint, p_worker_id uuid)
returns public.tasks language plpgsql security definer set search_path = '' as $$
declare
  v_task public.tasks;
  v_category_name text;
  v_pending_id bigint;
  v_in_progress_id bigint;
begin
  select id into v_pending_id from public.task_statuses where code = 'pending';
  select id into v_in_progress_id from public.task_statuses where code = 'in_progress';
  if v_pending_id is null or v_in_progress_id is null then
    raise exception 'Task status configuration is missing';
  end if;

  select t.* into v_task from public.tasks t
  where t.id = p_task_id and t.assigned_worker_id = p_worker_id
  for update;
  if not found then
    raise exception 'Assigned task was not found';
  end if;
  if v_task.status_id is distinct from v_pending_id then
    raise exception 'Task is not pending';
  end if;
  select category_name into v_category_name from public.task_categories where id = v_task.category_id;
  if v_category_name is distinct from 'Stock Check' then
    raise exception 'Task is not a stock check';
  end if;

  update public.tasks set status_id = v_in_progress_id, started_at = now()
  where id = p_task_id returning * into v_task;

  perform public.capture_stock_check_snapshot(p_task_id);
  return v_task;
end;
$$;

-- Replaces the counts and photos of an in-progress Stock Check task.
-- p_counts: [{ "size": "Small", "condition": "good", "quantity": 58, "damage_types": ["Bruised"] }, ...]
-- p_photos: [{ "size": "Small", "condition": "spoiled", "image_url": "...", "storage_path": "..." }, ...]
-- Every counted size and condition is required. Conditions that need a photo need one whenever their count is above zero.
create or replace function public.save_stock_check_submission(
  p_task_id bigint,
  p_worker_id uuid,
  p_counts jsonb,
  p_photos jsonb
)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_task public.tasks;
  v_category_name text;
  v_in_progress_id bigint;
  v_entry jsonb;
  v_size_id bigint;
  v_condition public.stock_conditions;
  v_quantity integer;
  v_expected integer;
  v_missing text;
begin
  select id into v_in_progress_id from public.task_statuses where code = 'in_progress';
  select t.* into v_task from public.tasks t
  where t.id = p_task_id and t.assigned_worker_id = p_worker_id
  for update;
  if not found then
    raise exception 'Assigned task was not found';
  end if;
  if v_task.status_id is distinct from v_in_progress_id then
    raise exception 'Only an active stock check can be submitted';
  end if;
  select category_name into v_category_name from public.task_categories where id = v_task.category_id;
  if v_category_name is distinct from 'Stock Check' then
    raise exception 'Task is not a stock check';
  end if;
  if not exists (select 1 from public.stock_check_snapshots where task_id = p_task_id) then
    perform public.capture_stock_check_snapshot(p_task_id);
  end if;
  if p_counts is null or jsonb_typeof(p_counts) <> 'array' then
    raise exception 'Stock counts are required';
  end if;

  delete from public.stock_check_counts where task_id = p_task_id;
  delete from public.stock_check_photos where task_id = p_task_id;

  for v_entry in select value from jsonb_array_elements(p_counts) loop
    select s.pineapple_size_id into v_size_id
    from public.stock_check_snapshots s
    join public.pineapple_sizes ps on ps.id = s.pineapple_size_id
    where s.task_id = p_task_id and lower(ps.size_name) = lower(coalesce(v_entry->>'size', ''));
    if v_size_id is null then
      raise exception 'Size % is not part of this stock check', coalesce(v_entry->>'size', '');
    end if;
    select * into v_condition from public.stock_conditions
    where code = coalesce(v_entry->>'condition', '') and status = true;
    if not found then
      raise exception 'Unknown condition %', coalesce(v_entry->>'condition', '');
    end if;
    if coalesce(v_entry->>'quantity', '') !~ '^\d{1,6}$' then
      raise exception 'Counts must be whole numbers 0 or greater';
    end if;
    v_quantity := (v_entry->>'quantity')::integer;
    insert into public.stock_check_counts (task_id, pineapple_size_id, condition_id, quantity, worker_quantity, damage_types)
    values (
      p_task_id, v_size_id, v_condition.id, v_quantity, v_quantity,
      coalesce(array(select jsonb_array_elements_text(case when jsonb_typeof(v_entry->'damage_types') = 'array' then v_entry->'damage_types' else '[]'::jsonb end)), '{}')
    )
    on conflict (task_id, pineapple_size_id, condition_id) do update
      set quantity = excluded.quantity, worker_quantity = excluded.worker_quantity,
          damage_types = excluded.damage_types, updated_at = now();
  end loop;

  select count(*) * (select count(*) from public.stock_conditions where status = true)
  into v_expected from public.stock_check_snapshots where task_id = p_task_id;
  if (select count(*) from public.stock_check_counts where task_id = p_task_id) <> v_expected then
    raise exception 'Enter a count for every size and condition';
  end if;

  if p_photos is not null and jsonb_typeof(p_photos) = 'array' then
    for v_entry in select value from jsonb_array_elements(p_photos) loop
      select s.pineapple_size_id into v_size_id
      from public.stock_check_snapshots s
      join public.pineapple_sizes ps on ps.id = s.pineapple_size_id
      where s.task_id = p_task_id and lower(ps.size_name) = lower(coalesce(v_entry->>'size', ''));
      select * into v_condition from public.stock_conditions where code = coalesce(v_entry->>'condition', '');
      if v_size_id is null or v_condition.id is null or coalesce(v_entry->>'image_url', '') = '' then
        raise exception 'A photo is missing its size, condition or image';
      end if;
      insert into public.stock_check_photos (task_id, pineapple_size_id, condition_id, image_url, storage_path)
      values (p_task_id, v_size_id, v_condition.id, v_entry->>'image_url', nullif(v_entry->>'storage_path', ''));
    end loop;
  end if;

  select ps.size_name || ', ' || sc.condition_name into v_missing
  from public.stock_check_counts c
  join public.stock_conditions sc on sc.id = c.condition_id
  join public.pineapple_sizes ps on ps.id = c.pineapple_size_id
  where c.task_id = p_task_id and c.quantity > 0 and sc.needs_photo
    and not exists (
      select 1 from public.stock_check_photos p
      where p.task_id = c.task_id and p.pineapple_size_id = c.pineapple_size_id and p.condition_id = c.condition_id
    )
  order by ps.id, sc.sort_order
  limit 1;
  if v_missing is not null then
    raise exception 'A photo is required for %', v_missing;
  end if;
end;
$$;

-- Approves a Stock Check task awaiting approval and corrects Pineapple Stock in one transaction.
-- p_counts (optional) holds the admin's corrections in the same shape as save_stock_check_submission.
-- For each size: final stock = current stock + good count - snapshot. The change is logged as
-- separate movements: pineapples found above the snapshot, each non-saleable condition, and pineapples unaccounted for.
create or replace function public.approve_stock_check_task(p_task_id bigint, p_admin_id uuid, p_counts jsonb)
returns public.tasks language plpgsql security definer set search_path = '' as $$
declare
  v_task public.tasks;
  v_category_name text;
  v_awaiting_id bigint;
  v_completed_id bigint;
  v_pineapple_category_id bigint;
  v_unit_id bigint;
  v_entry jsonb;
  v_size record;
  v_condition record;
  v_item_id bigint;
  v_total integer;
  v_available integer;
  v_extra integer;
  v_unaccounted integer;
begin
  select id into v_awaiting_id from public.task_statuses where code = 'awaiting_approval';
  select id into v_completed_id from public.task_statuses where code = 'completed';
  if v_awaiting_id is null or v_completed_id is null then
    raise exception 'Task status configuration is missing';
  end if;

  select t.* into v_task from public.tasks t where t.id = p_task_id for update;
  if not found then
    raise exception 'Task not found';
  end if;
  select category_name into v_category_name from public.task_categories where id = v_task.category_id;
  if v_task.status_id is distinct from v_awaiting_id then
    raise exception 'Task is not awaiting approval';
  end if;
  if v_category_name is distinct from 'Stock Check' then
    raise exception 'Task is not a stock check';
  end if;
  if not exists (select 1 from public.stock_check_counts where task_id = p_task_id) then
    raise exception 'This stock check has no counts to approve';
  end if;

  -- Admin corrections. The worker's own numbers stay in worker_quantity.
  if p_counts is not null and jsonb_typeof(p_counts) = 'array' then
    for v_entry in select value from jsonb_array_elements(p_counts) loop
      if coalesce(v_entry->>'quantity', '') !~ '^\d{1,6}$' then
        raise exception 'Counts must be whole numbers 0 or greater';
      end if;
      update public.stock_check_counts c set quantity = (v_entry->>'quantity')::integer, updated_at = now()
      from public.pineapple_sizes ps, public.stock_conditions sc
      where c.task_id = p_task_id and ps.id = c.pineapple_size_id and sc.id = c.condition_id
        and lower(ps.size_name) = lower(coalesce(v_entry->>'size', '')) and sc.code = coalesce(v_entry->>'condition', '');
    end loop;
  end if;

  select id into v_pineapple_category_id from public.inventory_categories where code = 'pineapple';
  select id into v_unit_id from public.measurement_units where abbreviation = 'pcs' and status = true;
  if v_pineapple_category_id is null or v_unit_id is null then
    raise exception 'Pineapple inventory is not configured';
  end if;

  perform set_config('agriverse.movement_task_id', p_task_id::text, true);

  for v_size in
    select s.pineapple_size_id as size_id, ps.size_name, s.system_quantity
    from public.stock_check_snapshots s
    join public.pineapple_sizes ps on ps.id = s.pineapple_size_id
    where s.task_id = p_task_id
    order by ps.id
  loop
    select coalesce(sum(quantity), 0) into v_total
    from public.stock_check_counts where task_id = p_task_id and pineapple_size_id = v_size.size_id;
    v_extra := greatest(v_total - v_size.system_quantity, 0);
    v_unaccounted := greatest(v_size.system_quantity - v_total, 0);

    v_item_id := public.stock_check_item_for_size(v_size.size_id);
    if v_item_id is null then
      if v_extra = 0 then
        continue;
      end if;
      insert into public.inventory_items (inventory_category_id, unit_id, item_name, quantity, created_by)
      values (v_pineapple_category_id, v_unit_id, v_size.size_name || ' Pineapple', 0, p_admin_id)
      returning id into v_item_id;
      insert into public.pineapple_inventory (inventory_id, size_id) values (v_item_id, v_size.size_id);
    end if;
    select quantity into v_available from public.inventory_items where id = v_item_id for update;

    if v_extra > 0 then
      perform set_config('agriverse.movement_reason', 'stock_check_found', true);
      perform set_config('agriverse.movement_condition_id', '', true);
      update public.inventory_items set quantity = quantity + v_extra where id = v_item_id;
      v_available := v_available + v_extra;
    end if;

    for v_condition in
      select c.condition_id, c.quantity
      from public.stock_check_counts c
      join public.stock_conditions sc on sc.id = c.condition_id
      where c.task_id = p_task_id and c.pineapple_size_id = v_size.size_id and not sc.stays_in_stock and c.quantity > 0
      order by sc.sort_order
    loop
      if v_available < v_condition.quantity then
        raise exception 'Not enough % Pineapple stock left to apply this count. Ask for a recount.', v_size.size_name;
      end if;
      perform set_config('agriverse.movement_reason', 'stock_check', true);
      perform set_config('agriverse.movement_condition_id', v_condition.condition_id::text, true);
      update public.inventory_items set quantity = quantity - v_condition.quantity where id = v_item_id;
      v_available := v_available - v_condition.quantity;
    end loop;

    if v_unaccounted > 0 then
      if v_available < v_unaccounted then
        raise exception 'Not enough % Pineapple stock left to apply this count. Ask for a recount.', v_size.size_name;
      end if;
      perform set_config('agriverse.movement_reason', 'stock_check_unaccounted', true);
      perform set_config('agriverse.movement_condition_id', '', true);
      update public.inventory_items set quantity = quantity - v_unaccounted where id = v_item_id;
    end if;
  end loop;

  perform set_config('agriverse.movement_reason', '', true);
  perform set_config('agriverse.movement_condition_id', '', true);
  perform set_config('agriverse.movement_task_id', '', true);

  update public.tasks set status_id = v_completed_id, approved_by = p_admin_id, approved_at = now()
  where id = p_task_id returning * into v_task;
  return v_task;
end;
$$;

