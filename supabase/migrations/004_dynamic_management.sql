-- Normalize task, schedule, and inventory configuration so managed values come
-- from database records instead of application source code.

create table if not exists public.task_categories (
  id bigint generated by default as identity primary key,
  category_name text not null,
  description text,
  status boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists task_categories_name_key
  on public.task_categories (lower(category_name));

create table if not exists public.task_priorities (
  id bigint generated by default as identity primary key,
  priority_name text not null,
  code text not null unique,
  status boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.task_statuses (
  id bigint generated by default as identity primary key,
  status_name text not null,
  code text not null unique,
  status boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.schedule_statuses (
  id bigint generated by default as identity primary key,
  status_name text not null,
  code text not null unique,
  status boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.farm_fields (
  id bigint generated by default as identity primary key,
  field_name text not null,
  description text,
  status boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists farm_fields_name_key on public.farm_fields (lower(field_name));

create table if not exists public.inventory_categories (
  id bigint generated by default as identity primary key,
  category_name text not null,
  code text not null unique,
  description text,
  status boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists inventory_categories_name_key
  on public.inventory_categories (lower(category_name));

create table if not exists public.measurement_units (
  id bigint generated by default as identity primary key,
  unit_name text not null,
  abbreviation text not null unique,
  status boolean not null default true,
  created_at timestamptz not null default now(),
