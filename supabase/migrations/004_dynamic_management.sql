create table if not exists public.schedules (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  schedule_date date not null,
  start_time time not null,
  end_time time not null,
  location text not null,
  status_id bigint not null references public.schedule_statuses(id) on delete restrict,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint schedules_time_order check (end_time > start_time),
  constraint schedules_notes_length check (notes is null or char_length(notes) <= 2000)
);
create unique index if not exists schedules_task_key on public.schedules(task_id);
create index if not exists schedules_date_idx on public.schedules(schedule_date, start_time);

insert into public.schedules (task_id, schedule_date, start_time, end_time, location, status_id, notes)
select t.id,
  (t.schedule_start at time zone 'Asia/Manila')::date,
  (t.schedule_start at time zone 'Asia/Manila')::time,
  case
    when ((t.schedule_start + make_interval(mins => t.estimated_duration_minutes)) at time zone 'Asia/Manila')::date
      > (t.schedule_start at time zone 'Asia/Manila')::date
    then time '24:00:00'
    else ((t.schedule_start + make_interval(mins => t.estimated_duration_minutes)) at time zone 'Asia/Manila')::time
  end,
  f.field_name,
  ss.id,
  t.description
from public.tasks t
join public.farm_fields f on f.id = t.field_id
join public.task_statuses ts on ts.id = t.status_id
join public.schedule_statuses ss on ss.code = case ts.code when 'pending' then 'scheduled' else ts.code end
on conflict (task_id) do nothing;

